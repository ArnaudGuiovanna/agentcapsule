-- An application's OIDC client, its issuer and client ID, serves the one
-- organization the platform operator approved it for (ADR 001, "Changes
-- after the v0.1.0 audit", finding S-10). Until v0.1.0 the first
-- organization to register an issuer and client ID held them: another
-- organization could take a client it does not own, and the 409 its owner
-- then got told it that the client was registered elsewhere. Now an
-- organization registers only a client approved for it, and a member's
-- token reaches the application of the organization its client is approved
-- for. The bundled Keycloak is one issuer for the whole installation: there
-- a client ID names a client the operator created in the shared realm, and
-- only the operator knows which organization it serves.
CREATE TABLE application_clients (
    id text PRIMARY KEY CHECK (id ~ '^apc_[0-9a-f]{32}$'),
    tenant_id text NOT NULL REFERENCES organizations(id),
    issuer text NOT NULL,
    client_id text NOT NULL,
    approved_by text NOT NULL CHECK (length(btrim(approved_by)) BETWEEN 1 AND 100),
    approved_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (issuer, client_id),
    UNIQUE (tenant_id, id)
);

-- Each existing registration keeps working: its client is approved for its
-- organization, by this migration. The operator reviews these approvals
-- (docs/api/applications.md).
INSERT INTO application_clients(id,tenant_id,issuer,client_id,approved_by)
  SELECT 'apc_'||replace(gen_random_uuid()::text,'-',''),tenant_id,issuer,client_id,'migration' FROM applications;

-- A client moves with its approval only. Withdrawing it disables the
-- application that used it, and another organization the client is then
-- approved for registers its own: an issuer and client ID are unique per
-- organization, and the approval names the one organization tokens reach.
ALTER TABLE applications DROP CONSTRAINT applications_issuer_client_id_key;
ALTER TABLE applications ADD CONSTRAINT applications_tenant_client UNIQUE (tenant_id, issuer, client_id);

ALTER TABLE organization_audit DROP CONSTRAINT organization_audit_action_check;
ALTER TABLE organization_audit ADD CONSTRAINT organization_audit_action_check
  CHECK (action IN ('organization.created','organization.disabled','organization.quotas_set',
                    'application_client.approved','application_client.withdrawn'));

